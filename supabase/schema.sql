CREATE TABLE IF NOT EXISTS users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL UNIQUE,
  name text NOT NULL DEFAULT 'Esther Lino',
  password_hash text NOT NULL,
  created_at text NOT NULL,
  updated_at text NOT NULL
);

CREATE TABLE IF NOT EXISTS sessions (
  token_hash text PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at text NOT NULL,
  created_at text NOT NULL
);

CREATE TABLE IF NOT EXISTS settings (
  key text PRIMARY KEY,
  value text NOT NULL
);

CREATE TABLE IF NOT EXISTS clients (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  phone text NOT NULL,
  phone_digits text NOT NULL,
  birth_date text,
  email text,
  notes text,
  active integer NOT NULL DEFAULT 1,
  created_at text NOT NULL,
  updated_at text NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_clients_name ON clients (lower(name));
CREATE INDEX IF NOT EXISTS idx_clients_phone ON clients (phone_digits);

CREATE TABLE IF NOT EXISTS anamneses (
  client_id bigint PRIMARY KEY REFERENCES clients(id) ON DELETE CASCADE,
  data text NOT NULL,
  consent integer NOT NULL DEFAULT 0,
  filled_at text,
  created_at text NOT NULL,
  updated_at text NOT NULL
);

CREATE TABLE IF NOT EXISTS procedures (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  description text,
  price_cents integer NOT NULL,
  duration_min integer NOT NULL,
  active integer NOT NULL DEFAULT 1,
  sort integer NOT NULL DEFAULT 0,
  created_at text NOT NULL,
  updated_at text NOT NULL
);

CREATE TABLE IF NOT EXISTS appointments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id bigint NOT NULL REFERENCES clients(id),
  date text NOT NULL,                 -- AAAA-MM-DD (horário de Brasília)
  start_at text NOT NULL,             -- AAAA-MM-DDTHH:MM:00-03:00
  end_at text NOT NULL,
  status text NOT NULL DEFAULT 'agendada',
  cancel_reason text,
  notes text,
  total_cents integer NOT NULL,
  duration_min integer NOT NULL,
  created_at text NOT NULL,
  updated_at text NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_appt_date ON appointments (date);
CREATE INDEX IF NOT EXISTS idx_appt_client ON appointments (client_id);

CREATE TABLE IF NOT EXISTS appointment_procedures (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  appointment_id bigint NOT NULL REFERENCES appointments(id) ON DELETE CASCADE,
  procedure_id bigint REFERENCES procedures(id),
  name text NOT NULL,                 -- valor e duração praticados no agendamento (RN08)
  price_cents integer NOT NULL,
  duration_min integer NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_ap_appt ON appointment_procedures (appointment_id);

CREATE TABLE IF NOT EXISTS blocks (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reason text NOT NULL,
  start_date text NOT NULL,
  end_date text NOT NULL,
  all_day integer NOT NULL DEFAULT 1,
  start_time text,
  end_time text,
  created_at text NOT NULL,
  updated_at text NOT NULL
);

CREATE TABLE IF NOT EXISTS transactions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type text NOT NULL CHECK (type IN ('in','out')),
  amount_cents integer NOT NULL CHECK (amount_cents > 0),
  date text NOT NULL,
  category text NOT NULL,
  method text,
  description text,
  client_id bigint REFERENCES clients(id),
  appointment_id bigint REFERENCES appointments(id) ON DELETE SET NULL,
  created_at text NOT NULL,
  updated_at text NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_tx_date ON transactions (date);

CREATE TABLE IF NOT EXISTS wa_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  appointment_id bigint NOT NULL UNIQUE REFERENCES appointments(id) ON DELETE CASCADE,
  phone text NOT NULL,
  jid text,
  status text NOT NULL,
  error text,
  reply text,
  reply_text text,
  sent_at text,
  replied_at text
);

-- sessão do WhatsApp conectado (para não precisar conectar de novo quando o servidor reinicia)
CREATE TABLE IF NOT EXISTS wa_auth (
  key text PRIMARY KEY,
  value text NOT NULL
);

CREATE TABLE IF NOT EXISTS stock_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  unit text NOT NULL DEFAULT 'un',
  quantity double precision NOT NULL DEFAULT 0,
  min_quantity double precision NOT NULL DEFAULT 0,
  active integer NOT NULL DEFAULT 1,
  created_at text NOT NULL,
  updated_at text NOT NULL
);

CREATE TABLE IF NOT EXISTS stock_moves (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id bigint NOT NULL REFERENCES stock_items(id) ON DELETE CASCADE,
  type text NOT NULL CHECK (type IN ('in','out')),
  quantity double precision NOT NULL CHECK (quantity > 0),
  date text NOT NULL,
  note text,
  created_at text NOT NULL
);

